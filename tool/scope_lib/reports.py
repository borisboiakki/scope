def _story_line(p: Project, sid: str) -> str:
    st = p.stories.get(sid)
    return f"{sid} [{st.status}] {st.title()}" if st else f"{sid} [missing]"


def status(p: Project) -> str:
    out = [f"phase: {p.state.get('phase')}"]
    cur = p.state.get("current") or {}
    out.append("current: " + ", ".join(f"{k}={v}" for k, v in cur.items() if v) if any(cur.values()) else "current: -")
    for name in ("brief", "spec", "architecture", "roadmap", "epics"):
        doc = p.docs.get(name)
        out.append(f"{name}: " + (f"{doc.status} v{doc.version}" if doc and doc.version else doc.status if doc else "-"))
    if p.waived("G3"):
        out.append("architecture gate G3: waived")
    for rel, d in p.releases.items():
        eps = p.epics_of_release(rel)
        sts = [s for e in eps for s in p.stories_of_epic(e) if s in p.stories]
        done = sum(p.stories[s].status == "done" for s in sts)
        out.append(f"{rel} [{d['status']}] epics {len(eps)}, stories {done}/{len(sts)} done"
                   + (", plan approved" if p.plan_approved(rel) else ""))
    for ep, d in p.epics.items():
        if d["status"] in ("launched", "blocked", "ready"):
            out.append(f"  {ep} [{d['status']}] {d['title']}")
    blockers = [b for b in p.state["blockers"] if not b.get("resolved")]
    for b in blockers:
        out.append(f"BLOCKER {b['story']} {b['code']}: {b['summary']}")
    open_items = [i for i, r in p.register.items() if r["status"] == "open"]
    if open_items:
        out.append(f"register open: {', '.join(open_items)} (blocking: {', '.join(p.blocking_items()) or 'none'})")
    open_crs = [c for c, d in p.crs.items() if d.status in ("proposed", "approved")]
    if open_crs:
        out.append(f"open CRs: {', '.join(open_crs)}")
    out.append("next: " + next_step(p))
    return "\n".join(out)


def next_step(p: Project) -> str:
    if any(not b.get("resolved") for b in p.state["blockers"]):
        return "resolve the open blocker with the human, then scope.py story unblock ST-n"
    for name, skill in (("brief", "scope-spec (brief)"), ("spec", "scope-spec (spec)")):
        doc = p.docs.get(name)
        if not doc:
            return f"write the {name}: {skill}"
        if doc.status != "approved":
            return f"finish the {name}, then ask the human to approve it (approve {name})"
    arch = p.docs.get("architecture")
    if not p.waived("G3") and (not arch or arch.status != "approved"):
        return "write the architecture: scope-arch" if not arch else "ask the human to approve the architecture"
    if "roadmap" not in p.docs or "epics" not in p.docs:
        return "plan releases, epics and stories: scope-plan"
    for rel, d in p.releases.items():
        if d["status"] == "released":
            continue
        if not p.plan_approved(rel) or p.docs["roadmap"].status != "approved":
            return f"finish the plan of {rel}, then ask the human: approve plan {rel}"
        eps = p.epics_of_release(rel)
        for ep in eps:
            st = p.epics[ep]["status"]
            if st == "launched":
                ready = [s for s in p.stories_of_epic(ep) if s in p.stories and p.stories[s].status in
                         ("in-progress", "in-review", "ready", "needs-rework")]
                return f"build {ep}: next story {ready[0]}" if ready else f"build {ep}"
        for ep in eps:
            if p.epics[ep]["status"] == "ready":
                return f"ask the human to launch {ep} (approve launch {ep} --mode supervised|autonomous)"
        if all(p.epics[e]["status"] == "done" for e in eps):
            return f"all epics of {rel} done: ask the human to close it (approve release-close {rel})"
        return f"{rel}: check epic statuses"
    return "all releases closed: plan the next release (scope-plan) or stop"


def trace(p: Project) -> str:
    lines = ["# Traceability", "", f"Generated by scope.py on {today()}. Do not edit.", ""]
    rels = list(p.releases) + ["later"]
    for rel in rels:
        reqs = [r for r, q in p.reqs.items() if p.effective_release(r) == rel or (rel == "later" and
                q["release"].lower() == "later")]
        if not reqs:
            continue
        lines += [f"## {rel}", "", "| Requirement | Source | Acceptance criteria | Stories | Done |", "|---|---|---|---|---|"]
        for r in sort_ids(reqs):
            q = p.reqs[r]
            sts = p.stories_implementing(r)
            sts_txt = ", ".join(f"{s} ({p.stories[s].status})" for s in sts) or "—"
            title = q["title"] + (" ~~removed~~" if q["removed"] else "")
            lines.append(f"| {r} {title} | {', '.join(q['sources']) or '—'} | {', '.join(q['acs']) or '—'} | "
                         f"{sts_txt} | {'yes' if p.req_done(r) else 'no'} |")
        lines.append("")
    write(p.dir / "reports" / "trace.md", "\n".join(lines))
    return "wrote docs/scope/reports/trace.md"


def remaining(p: Project) -> str:
    lines = ["# Remaining work", "", f"Generated by scope.py on {today()}. Do not edit.", ""]
    summary = []
    for rel in list(p.releases) + ["later"]:
        reqs = [r for r, q in p.reqs.items() if not q["removed"] and not p.req_done(r)
                and (p.effective_release(r) == rel or (rel == "later" and q["release"].lower() == "later"))]
        if rel != "later" and p.releases[rel]["status"] == "released" and not reqs:
            continue
        eps = p.epics_of_release(rel) if rel != "later" else []
        open_sts = [s for e in eps for s in p.stories_of_epic(e) if s in p.stories and
                    p.stories[s].status not in ("done", "removed")]
        if not reqs and not open_sts:
            continue
        status = p.releases[rel]["status"] if rel in p.releases else "-"
        lines += [f"## {rel} ({status})", ""]
        lines += [f"- {r} {p.reqs[r]['title']} — stories: {', '.join(p.stories_implementing(r)) or 'none'}"
                  for r in sort_ids(reqs)]
        lines += [f"- {_story_line(p, s)}" for s in open_sts]
        lines.append("")
        summary.append(f"{rel}: {len(reqs)} requirement(s), {len(open_sts)} story(ies) open")
    for c in p.state.get("carryover", []):
        lines.append(f"- carried {c['from']} -> {c['to']}: {', '.join(c['items'])} ({c['reason']})")
    crs = [f"{c} [{d.status}]" for c, d in p.crs.items() if d.status in ("proposed", "approved")]
    reg = [f"{i} [{'blocking' if r['blocking'] in ('yes', 'y', 'true') else 'non-blocking'}] {r['statement']}"
           for i, r in p.register.items() if r["status"] == "open"]
    if crs:
        lines += ["## Open change requests", ""] + [f"- {c}" for c in crs] + [""]
    if reg:
        lines += ["## Open assumptions and questions", ""] + [f"- {x}" for x in reg] + [""]
    summary.append(f"open CRs: {len(crs)}, open register items: {len(reg)}")
    write(p.dir / "reports" / "remaining.md", "\n".join(lines))
    return "\n".join(summary + ["wrote docs/scope/reports/remaining.md"])


def impact(p: Project, ids: list[str]) -> str:
    out = []
    for ident in ids:
        reqs, stories, adrs = set(), set(), set()
        if ident.startswith("BR-"):
            reqs = {r for r, q in p.reqs.items() if ident in q["sources"]}
        elif ident.startswith(("FR-", "NFR-")):
            reqs = {p.req_of(ident)}
        elif ident.startswith("ADR-"):
            adrs = {ident}
            stories = {s for s, d in p.stories.items() if ident in id_list(d.fm.get("adrs"))}
        elif ident.startswith("ST-"):
            stories = {ident} | {s for s, d in p.stories.items() if ident in id_list(d.fm.get("depends_on"))}
        elif ident.startswith("EP-"):
            stories = set(p.stories_of_epic(ident))
        elif re.fullmatch(r"R\d+", ident):
            stories = {s for e in p.epics_of_release(ident) for s in p.stories_of_epic(e)}
            reqs = {r for r in p.reqs if p.effective_release(r) == ident}
        elif ident.startswith(("ASM-", "OQ-")):
            row = p.register.get(ident)
            if not row:
                raise ScopeError(f"{ident} not in register.md")
            out.append(f"{ident}: impacts {', '.join(row['impacts']) or 'nothing listed'}")
            for sub in row["impacts"]:
                out.append(impact(p, [sub]))
            continue
        else:
            raise ScopeError(f"impact: unsupported id {ident}")
        for r in reqs:
            stories |= set(p.stories_implementing(r))
            adrs |= {a for a, d in p.adrs.items() if r in id_list(d.fm.get("relates_to"))}
        epics = sort_ids({str(p.stories[s].fm.get("epic")) for s in stories if s in p.stories})
        rels = sort_ids({p.epics[e]["release"] for e in epics if e in p.epics} |
                        {p.effective_release(r) for r in reqs if p.effective_release(r).startswith("R")})
        crs = [c for c, d in p.crs.items() if ident in id_list(d.fm.get("affects"))]
        reg = [i for i, row in p.register.items() if ident in row["impacts"] or reqs & set(row["impacts"])]
        arch = "yes" if "architecture" in p.docs and ident in ids_in(p.docs["architecture"].text) else "no"
        out.append(f"{ident}:")
        out.append(f"  requirements: {', '.join(sort_ids(reqs)) or '-'}")
        out.append("  stories: " + (", ".join(f"{s} [{p.stories[s].status}]" for s in sort_ids(stories)
                                              if s in p.stories) or "-"))
        out.append(f"  epics: {', '.join(epics) or '-'}; releases: {', '.join(rels) or '-'}")
        out.append(f"  ADRs: {', '.join(sort_ids(adrs)) or '-'}; architecture mentions it: {arch}")
        out.append(f"  CRs: {', '.join(crs) or '-'}; register: {', '.join(reg) or '-'}")
    return "\n".join(out)


def extract(p: Project, ids: list[str]) -> str:
    parts = []
    for ident in ids:
        if ident in p.reqs:
            parts.append(p.reqs[ident]["text"])
        elif ident in p.acs:
            parts.append(f"{p.acs[ident]['req']} {p.reqs[p.acs[ident]['req']]['title']}: {p.acs[ident]['text']}")
        elif ident in p.brs:
            parts.append(p.brs[ident]["text"])
        elif ident in p.adrs:
            parts.append(p.adrs[ident].body.strip())
        elif ident in p.stories:
            parts.append(p.stories[ident].definition().strip())
        elif ident in p.epics:
            parts.append(p.epics[ident]["text"])
        elif ident in p.releases:
            parts.append(p.releases[ident]["text"])
        elif ident in p.register:
            parts.append(p.register[ident]["line"])
        elif ident in p.crs:
            parts.append(p.crs[ident].body.strip())
        else:
            raise ScopeError(f"extract: {ident} not found")
    return "\n\n".join(strip_comments(x).strip() for x in parts)


def next_id(p: Project, prefix: str) -> str:
    m = re.fullmatch(r"((?:FR|NFR)-\d+)\.", prefix)
    if m:
        if m.group(1) not in p.reqs:
            raise ScopeError(f"{m.group(1)} not in spec.md")
        nums = [int(a.split(".")[1]) for a in p.reqs[m.group(1)]["acs"]]
        return f"{m.group(1)}.{max(nums, default=0) + 1}"
    prefix = prefix.rstrip("-")
    if prefix not in ("BR", "FR", "NFR", "ADR", "EP", "ST", "CR", "ASM", "OQ", "R"):
        raise ScopeError("prefix must be BR, FR, NFR, ADR, EP, ST, CR, ASM, OQ, R or FR-n. (acceptance criterion)")
    seen = set()
    for doc in p.all_files():
        seen.update(ids_in(doc.text))
        seen.add(getattr(doc, "file_id", None) or "")
    pat = re.compile(rf"^{prefix}(?:-)?(\d+)$" if prefix == "R" else rf"^{prefix}-(\d+)$")
    nums = [int(m.group(1)) for i in seen if i and (m := pat.match(i))]
    sep = "" if prefix == "R" else "-"
    return f"{prefix}{sep}{max(nums, default=0) + 1}"


def register_add(p: Project, kind: str, statement: str, raised: str, blocking: bool, impacts: list[str]) -> str:
    if kind not in ("ASM", "OQ"):
        raise ScopeError("--type must be ASM or OQ")
    if "|" in statement or "|" in raised:
        raise ScopeError("the text must not contain '|'")
    doc = p.docs.get("register")
    if not doc:
        raise ScopeError("docs/scope/register.md not found")
    new_id = next_id(p, kind)
    row = (f"| {new_id} | {statement} | {raised} | {'yes' if blocking else 'no'} | {', '.join(impacts) or '—'} "
           f"| open | |")
    text = read(doc.path).rstrip("\n") + "\n" + row + "\n"
    write(doc.path, text)
    return new_id


def register_set(p: Project, ident: str, status: str | None, resolution: str | None, blocking: str | None) -> str:
    row = p.register.get(ident)
    if not row:
        raise ScopeError(f"{ident} not in register.md")
    if status and status not in ("open", "validated", "invalidated", "answered", "closed"):
        raise ScopeError("status must be open, validated, invalidated, answered or closed")
    if resolution and "|" in resolution:
        raise ScopeError("the text must not contain '|'")
    cells = [c.strip() for c in row["line"].strip().strip("|").split("|")]
    cells += [""] * (7 - len(cells))
    if status:
        cells[5] = status
    if blocking:
        cells[3] = "yes" if blocking.lower() in ("yes", "y", "true") else "no"
    if resolution:
        cells[6] = f"{resolution} ({today()})"
    new_line = "| " + " | ".join(cells[:7]) + " |"
    doc = p.docs["register"]
    write(doc.path, read(doc.path).replace(row["line"], new_line, 1))
    msg = f"{ident} -> {cells[5]}"
    if status == "invalidated":
        msg += f"\nassumption invalidated: run scope.py impact {ident} and propose a CR (scope-change)"
    return msg


def register_list(p: Project, only_open: bool) -> str:
    rows = [(i, r) for i, r in p.register.items() if not only_open or r["status"] == "open"]
    if not rows:
        return "register: no item" + (" open" if only_open else "")
    return "\n".join(f"{i} [{r['status']}{', blocking' if r['blocking'] in ('yes', 'y', 'true') else ''}] "
                     f"{r['statement']}" for i, r in sorted(rows, key=lambda x: (x[0].split('-')[0], id_number(x[0]))))


def release_notes(p: Project, rel: str, open_stories, open_reqs, carry, reason) -> str:
    d = p.releases[rel]
    done_reqs = [r for r, q in p.reqs.items() if p.effective_release(r) == rel and p.req_done(r)]
    lines = [f"# Release {rel} — {d['title']}", "", f"Closed on {today()}.", ""]
    lines += ["## Delivered requirements", ""] + [f"- {r} {p.reqs[r]['title']}" for r in sort_ids(done_reqs)] + [""]
    sts = [s for e in p.epics_of_release(rel) for s in p.stories_of_epic(e) if s in p.stories
           and p.stories[s].status == "done"]
    lines += ["## Stories", ""] + [f"- {_story_line(p, s)}" for s in sts] + [""]
    crs = [c for c, x in p.crs.items() if x.status == "applied"]
    if crs:
        lines += ["## Applied change requests", ""] + [f"- {c} {p.crs[c].title()}" for c in crs] + [""]
    if open_stories or open_reqs:
        lines += [f"## Carried over to {carry}", "", f"Reason: {reason}", ""]
        lines += [f"- {x}" for x in sort_ids(open_reqs + open_stories)] + [""]
    reg = [i for i, r in p.register.items() if r["status"] == "open"]
    if reg:
        lines += ["## Open assumptions and questions", ""] + [f"- {i} {p.register[i]['statement']}" for i in reg] + [""]
    return "\n".join(lines)
